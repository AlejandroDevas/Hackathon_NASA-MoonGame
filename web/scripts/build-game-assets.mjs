// Builds the local copies of what the game used to load from the internet, so it works offline:
//   public/juego/tailwind.css  Tailwind (v3, the same one the CDN served), compiled for the classes the page uses
//   public/juego/fonts.css     @font-face rules for Fredoka and JetBrains Mono
//   public/juego/fonts/*.woff2 the Latin subsets of those fonts (SIL Open Font License, from @fontsource)
// Run it with `npm run build-game` whenever public/juego/index.html changes its classes; the output is committed.
import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const WEB = join(dirname(fileURLToPath(import.meta.url)), '..');
const GAME = join(WEB, 'public', 'juego');
const require = createRequire(import.meta.url);

// ---- Tailwind
const work = mkdtempSync(join(tmpdir(), 'game-tailwind-'));
try {
  const input = join(work, 'input.css');
  const config = join(work, 'tailwind.config.cjs');
  writeFileSync(input, '@tailwind base;\n@tailwind components;\n@tailwind utilities;\n');
  writeFileSync(config, `module.exports = { content: [${JSON.stringify(join(GAME, 'index.html'))}], theme: { extend: {} }, plugins: [] };\n`);
  const cli = require.resolve('tailwindcss/lib/cli.js');
  execFileSync(process.execPath, [cli, '-c', config, '-i', input, '-o', join(GAME, 'tailwind.css'), '--minify'], { stdio: 'inherit' });
} finally {
  rmSync(work, { recursive: true, force: true });
}

// ---- fonts
const FONTS = [
  { family: 'Fredoka', pkg: 'fredoka', file: 'fredoka', weights: [500, 600, 700] },
  { family: 'JetBrains Mono', pkg: 'jetbrains-mono', file: 'jetbrains-mono', weights: [500, 700] },
];
mkdirSync(join(GAME, 'fonts'), { recursive: true });
let css = '/* Generated by web/scripts/build-game-assets.mjs. Fonts: SIL Open Font License 1.1 (via @fontsource). */\n';
for (const { family, pkg, file, weights } of FONTS) {
  const dir = dirname(require.resolve(`@fontsource/${pkg}/package.json`));
  for (const weight of weights) {
    const name = `${file}-latin-${weight}-normal.woff2`;
    copyFileSync(join(dir, 'files', name), join(GAME, 'fonts', name));
    css += `@font-face { font-family: '${family}'; font-style: normal; font-display: swap; font-weight: ${weight}; src: url('./fonts/${name}') format('woff2'); }\n`;
  }
}
writeFileSync(join(GAME, 'fonts.css'), css);
console.log('game assets ready in public/juego');
